/** 지금 상태(staffStatus 글)와 시각으로 기분을 고른다. 밤 10시~새벽 6시는 늦은 밤 */
export function chatMood(status: string, hour: number): ChatMood {
  if (hour >= 22 || hour < 6) return 'lateNight';
  if (status.includes('막힘')) return 'blocked';
  if (status === '대기 중' || status === '정지' || status.includes('멈춤')) return 'idle';
  return 'busy';
}
